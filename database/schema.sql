CREATE DATABASE IF NOT EXISTS sop_chatbot CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sop_chatbot;

CREATE TABLE IF NOT EXISTS sops (
  id VARCHAR(64) PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  filename VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL DEFAULT 'Custom Policy',
  content LONGTEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS chat_sessions (
  id VARCHAR(64) PRIMARY KEY,
  title VARCHAR(255) NOT NULL DEFAULT 'New Session',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  session_id VARCHAR(64) NOT NULL,
  sender ENUM('user','assistant') NOT NULL,
  content LONGTEXT NOT NULL,
  image LONGTEXT NULL,
  confidence_score DECIMAL(5,4) NULL,
  model_used VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_session (session_id),
  CONSTRAINT fk_chat_session FOREIGN KEY (session_id)
    REFERENCES chat_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS uploaded_docs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  filename VARCHAR(255) NOT NULL UNIQUE,
  category VARCHAR(50) NOT NULL DEFAULT 'Custom Policy',
  chunks INT NOT NULL DEFAULT 0,
  bytes BIGINT NOT NULL DEFAULT 0,
  uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;